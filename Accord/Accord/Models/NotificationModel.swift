import Foundation

/// A model that abstracts a local notification.
///
/// It carries only the text that will be displayed; how and when it is delivered is decided by
/// ``NotificationScheduling``.
struct NotificationModel: Equatable {

    /// Identifier used for the notification request.
    var id: UUID

    /// Main text of the notification.
    var title: String

    /// Secondary text, displayed below the title.
    var subtitle: String

    /// Detailed text of the notification.
    var body: String

    /// Creates a notification model.
    ///
    /// - Parameters:
    ///   - id: The identifier of the notification. A new one is generated by default.
    ///   - title: The main text of the notification.
    ///   - subtitle: The secondary text of the notification.
    ///   - body: The detailed text of the notification.
    init(id: UUID = UUID(), title: String, subtitle: String, body: String) {
        self.id = id
        self.title = title
        self.subtitle = subtitle
        self.body = body
    }
}
